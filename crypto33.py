def hex_to_bin(hex_str: str, bits: int = 64) -> str:
  return f"{int(hex_str, 16):0{bits}b}"


def bin_to_hex(bin_str: str) -> str:
  return f"{int(bin_str, 2):0{len(bin_str) // 4}X}"


def permute(bits: str, table: tuple) -> str:
  return "".join(bits[i - 1] for i in table)


def xor(a: str, b: str) -> str:
  return "".join("1" if x != y else "0" for x, y in zip(a, b))


def left_shift(bits: str, n: int) -> str:
  return bits[n:] + bits[:n]


def generate_round_keys(key_64bit: str) -> list[str]:
  # Drops 8 parity bits via PC-1 to produce a 56-bit key[cite: 1]
  key_56bit = permute(key_64bit, PC1)
  c, d = key_56bit[:28], key_56bit[28:]
  round_keys = []
  for shift in SHIFTS:
    c = left_shift(c, shift)
    d = left_shift(d, shift)
    round_keys.append(permute(c + d, PC2))
  return round_keys


def feistel(right_32bit: str, subkey_48bit: str) -> str:
  expanded = permute(right_32bit, E)
  xored = xor(expanded, subkey_48bit)
  sbox_output = []
  for i in range(8):
    chunk = xored[i * 6 : (i + 1) * 6]
    row = int(chunk[0] + chunk[5], 2)
    col = int(chunk[1:5], 2)
    sbox_output.append(f"{S_BOXES[i][row][col]:04b}")
  return permute("".join(sbox_output), P)


def des_process_block(block_64bit: str, round_keys: list[str], decrypt: bool = False) -> str:
  # Uses the exact same algorithm for encryption and decryption, reversing subkey order for decryption[cite: 1]
  keys = round_keys[::-1] if decrypt else round_keys
  permuted = permute(block_64bit, IP)
  left, right = permuted[:32], permuted[32:]

  for subkey in keys:
    left, right = right, xor(left, feistel(right, subkey))

  # Final 32-bit swap before inverse initial permutation (FP)
  combined = right + left
  return permute(combined, FP)


